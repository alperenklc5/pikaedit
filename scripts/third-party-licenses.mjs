#!/usr/bin/env node
/**
 * scripts/third-party-licenses.mjs
 *
 * Writes THIRD_PARTY_LICENSES.md from package-lock.json (lockfile v3 records
 * "license", "dev" and "optional" for every package, including platform
 * binaries that are not installed on the current OS).
 *
 * --check   also compare the lockfile license with node_modules/<pkg>/package.json
 *           for every installed package and exit 1 on a mismatch.
 *
 * Run: node scripts/third-party-licenses.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(ROOT, "package-lock.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const CHECK = process.argv.includes("--check");

const COPYLEFT = /GPL|SSPL|Commons Clause|BUSL|EUPL|MPL|CC-BY-NC|CC-BY-SA/i;

// Older packages declare `licenses: [{ type }]`, which npm does not copy into
// the lockfile; read it from node_modules when the package is installed.
const legacyLicense = (key) => {
  const pj = join(ROOT, key, "package.json");
  if (!existsSync(pj)) return undefined;
  const j = JSON.parse(readFileSync(pj, "utf8"));
  if (Array.isArray(j.licenses)) return j.licenses.map((l) => l.type ?? l).join(" OR ");
  return undefined;
};

const rows = [];
for (const [key, info] of Object.entries(lock.packages)) {
  if (!key) continue; // the root project
  const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
  rows.push({
    name,
    version: info.version,
    license: info.license ?? legacyLicense(key) ?? "(not recorded)",
    scope: info.dev ? "dev" : "runtime",
    optional: Boolean(info.optional),
    path: key,
  });
}

// De-duplicate identical name@version (nested copies)
const unique = new Map();
for (const r of rows) unique.set(`${r.name}@${r.version}@${r.scope}`, r);
const list = [...unique.values()].sort((a, b) => a.name.localeCompare(b.name));

let mismatches = 0;
if (CHECK) {
  for (const r of rows) {
    const pj = join(ROOT, r.path, "package.json");
    if (!existsSync(pj)) continue; // optional platform binary not installed here
    const j = JSON.parse(readFileSync(pj, "utf8"));
    const actual = j.license ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type ?? l).join(" OR ") : "(not recorded)");
    if (actual !== r.license) {
      console.log(`MISMATCH ${r.path}: lock=${r.license} node_modules=${actual}`);
      mismatches++;
    }
  }
}

const count = (scope) => {
  const c = {};
  for (const r of list.filter((x) => x.scope === scope)) c[r.license] = (c[r.license] ?? 0) + 1;
  return Object.entries(c).sort((a, b) => b[1] - a[1]);
};
const direct = (deps, scope) =>
  Object.keys(deps)
    .sort()
    .map((n) => {
      const info = lock.packages[`node_modules/${n}`];
      return `| ${n} | ${info.version} | ${info.license ?? "(not recorded)"} | ${scope} |`;
    });

const runtime = list.filter((r) => r.scope === "runtime");
const nonMitRuntime = runtime.filter((r) => r.license !== "MIT");
const copyleft = list.filter((r) => COPYLEFT.test(r.license));

const md = `# Third-party licenses

Generated by \`node scripts/third-party-licenses.mjs\` from \`package-lock.json\`
(lockfile v${lock.lockfileVersion}). The \`license\` values are the SPDX identifiers
declared by each package; they are not legal advice. This repository's own code
is MIT-licensed (see LICENSE). No third-party code is vendored into this
repository: dependencies are installed from npm.

## Direct dependencies

| Package | Version | License | Scope |
|---|---|---|---|
${[...direct(pkg.dependencies, "runtime"), ...direct(pkg.devDependencies, "dev")].join("\n")}

## All installed packages by license

Runtime (dependencies of the app, ${runtime.length} packages, including optional
platform binaries such as \`@next/swc-*\` and \`@libsql/<platform>\`):

| License | Packages |
|---|---|
${count("runtime").map(([l, n]) => `| ${l} | ${n} |`).join("\n")}

Development only (build, lint and type tooling, ${list.length - runtime.length} packages):

| License | Packages |
|---|---|
${count("dev").map(([l, n]) => `| ${l} | ${n} |`).join("\n")}

## Copyleft or restricted licenses

${copyleft.length ? copyleft.map((r) => `- ${r.name}@${r.version}: ${r.license} (${r.scope})`).join("\n") : "None (no GPL, LGPL, AGPL, MPL, SSPL, BUSL, EUPL, Commons Clause or CC-BY-NC/SA packages in the lockfile)."}

## Runtime packages under a license other than MIT

These permissive licenses require keeping their copyright and license notices
when the packages are redistributed (they are, inside \`node_modules\`).

| Package | Version | License |
|---|---|---|
${nonMitRuntime.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}

Notes:
- \`caniuse-lite\` (CC-BY-4.0) is browser-support data used by Next.js at build time.
- \`libsql\` (MIT) provides the native SQLite/libSQL binding used by
  \`@libsql/client\`; its LICENSE lists Joshua Wise (2017) and Pekka Enberg (2023).
- \`busboy\` and \`streamsearch\` declare MIT in the older \`licenses\` field,
  which the lockfile does not record; the script reads it from node_modules.
- \`axe-core\` (MPL-2.0) is a development-only dependency of
  \`eslint-config-next\` (via eslint-plugin-jsx-a11y). It is used by the linter
  and is not part of the built application.
`;

writeFileSync(join(ROOT, "THIRD_PARTY_LICENSES.md"), md);
console.log(`THIRD_PARTY_LICENSES.md written: ${list.length} unique packages (${runtime.length} runtime), copyleft: ${copyleft.length}`);
if (CHECK) {
  console.log(mismatches ? `${mismatches} lock/node_modules license mismatch(es)` : "lock vs node_modules: all installed licenses match");
  if (mismatches) process.exit(1);
}
